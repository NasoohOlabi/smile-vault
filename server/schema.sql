CREATE TABLE IF NOT EXISTS storefront (
  singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
  navigation jsonb NOT NULL CHECK (jsonb_typeof(navigation) = 'object'),
  copy jsonb NOT NULL CHECK (jsonb_typeof(copy) = 'object'),
  revision integer NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  details jsonb NOT NULL CHECK (jsonb_typeof(details) = 'object'),
  published boolean NOT NULL DEFAULT true,
  revision integer NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS assets (
  id uuid PRIMARY KEY,
  name text NOT NULL,
  mime text NOT NULL CHECK (mime IN ('image/jpeg', 'image/png', 'image/webp', 'image/gif')),
  bytes bytea NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS orders (
  id uuid PRIMARY KEY,
  request_hash text NOT NULL,
  customer jsonb NOT NULL CHECK (jsonb_typeof(customer) = 'object'),
  items jsonb NOT NULL CHECK (jsonb_typeof(items) = 'array'),
  total integer NOT NULL CHECK (total >= 0),
  status text NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'confirmed', 'fulfilled', 'cancelled')),
  created_at timestamptz NOT NULL DEFAULT now(),
  revision integer NOT NULL DEFAULT 1
);

CREATE INDEX IF NOT EXISTS orders_recent ON orders (created_at DESC, id DESC);
